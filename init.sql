-- Create Tables
CREATE TABLE SALARY_ENTRY (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPANY_NAME VARCHAR2(255),
    TOTAL_SALARY BINARY_DOUBLE,
    MONTH VARCHAR2(255),
    YEAR NUMBER(10,0)
);

CREATE TABLE EMERGENCY_FUND (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRIPTION VARCHAR2(255),
    AMOUNT BINARY_DOUBLE,
    FUND_DATE DATE
);

CREATE TABLE EXPENSE (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRIPTION VARCHAR2(255),
    AMOUNT BINARY_DOUBLE,
    EXPENSE_DATE DATE
);

CREATE TABLE GOALS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRIPTION VARCHAR2(255),
    TYPE VARCHAR2(255),
    STATUS VARCHAR2(255)
);

CREATE TABLE PRECIOUS_METAL_ENTRY (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TYPE VARCHAR2(255),
    WEIGHT BINARY_DOUBLE,
    PRICE BINARY_DOUBLE,
    PURCHASE_DATE VARCHAR2(255),
    PURITY VARCHAR2(255)
);

CREATE TABLE PROJECT (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255),
    START_DATE DATE,
    END_DATE DATE,
    COMPANY_NAME VARCHAR2(255)
);

CREATE TABLE RECURRING_DEPOSIT_ENTRY (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255),
    MONTHLY_AMOUNT BINARY_DOUBLE,
    START_DATE DATE,
    TENURE_MONTHS NUMBER(10,0),
    INTEREST_RATE BINARY_DOUBLE,
    STATUS VARCHAR2(255)
);

CREATE TABLE SAVINGS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRIPTION VARCHAR2(255),
    AMOUNT BINARY_DOUBLE,
    SAVINGS_DATE DATE
);

